def narrator_zh(n):
    if n in NARR:
        return NARR[n]
    if any(ord(c) > 127 for c in n) and "/" not in n:
        raise SystemExit(f"unmapped narrator: {n}")
    return n

def write_one(name, title_zh, sub_zh, zhs):
    src_path = SRC / name
    dst_path = DST / name
    if dst_path.exists():
        print("skip", name)
        return
    src = json.loads(src_path.read_text(encoding="utf-8"))
    entries = src["entry"]
    if len(entries) != len(zhs):
        raise SystemExit(f"{name}: source {len(entries)} zh {len(zhs)}")
    out_entries = []
    for i, (e, zh) in enumerate(zip(entries, zhs)):
        if not isinstance(zh, str) or zh == "":
            raise SystemExit(f"{name} empty zh at {i}: {e['text']}")
        if "\u7efd" in zh:
            raise SystemExit(f"{name} bad ayami char at {i}: {zh}")
        if e["text"].count("\n") != zh.count("\n"):
            raise SystemExit(
                f"{name} newline mismatch at {i}: src {e['text'].count(chr(10))} zh {zh.count(chr(10))}\nSRC:{e['text']!r}\nZH:{zh!r}"
            )
        nz = narrator_zh(e["narrator"])
        if nz == "雅":
            for bad in ("\u567b", "\u54fd", "\u5566"):
                if bad in zh:
                    raise SystemExit(f"{name} forbidden particle at {i}: {zh}")
        if "アーヤ" in e["text"] and A not in zh and "綾水" not in e["text"]:
            # name should appear when she is addressed by the short name
            if e["narrator"] != "アーヤ":
                print(f"note {name} #{i} アーヤ not in zh: {e['text']} -> {zh}")
        out_entries.append({
            "location": e["location"],
            "narrator": e["narrator"],
            "text": e["text"],
            "zh": zh,
            "narrator_zh": nz,
        })
    info = dict(src["info"])
    info["title_zh"] = title_zh
    info["sub_title_zh"] = sub_zh
    out = {"dir": src["dir"], "type": src["type"], "info": info, "entry": out_entries}
    dst_path.write_text(json.dumps(out, ensure_ascii=False, indent=4) + "\n", encoding="utf-8")
    print("wrote", name, len(out_entries))

